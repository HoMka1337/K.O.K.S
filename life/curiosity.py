class Curiosity:
    def __init__(self, journal, goals):
        self.journal = journal
        self.goals = goals

    def bootstrap(self, min_goals: int = 3) -> None:
        active = self.goals.active()
        if len(active) >= min_goals:
            return
        pool = STARTER_GOALS[:]
        random.shuffle(pool)
        added = 0
        for text in pool:
            if len(self.goals.active()) >= min_goals:
                break
            try:
                self.goals.add(text, source="bootstrap", priority=1)
                self.journal.add("goal", text, source="bootstrap")
                added += 1
            except ValueError:
                continue
        if added == 0:
            self._random_topic_goal()

    def _random_topic_goal(self) -> None:
        topic = random.choice(TOPIC_SEEDS)
        text = f"узнать что такое {topic}"
        try:
            self.goals.add(text, source="curiosity", priority=1)
            self.journal.add("goal", text, source="curiosity")
        except ValueError:
            pass

    def from_errors(self) -> None:
        errors = self.journal.last_errors(limit=3)
        for entry in errors:
            content = entry.get("content", "")
            if not content:
                continue
            self.journal.add("thought", f"видел ошибку: {content[:80]}")

    def from_unknown_words(self, text: str) -> None:
        if self._looks_like_error(text):
            return
        words = re.findall(r"[А-Яа-яA-Za-z]{6,}", text)
        if not words:
            return
        added = 0
        for word in words[:2]:
            w = word.lower()
            if w in STOPWORDS:
                continue
            text_goal = f"узнать что такое {word}"
            try:
                self.goals.add(text_goal, source="curiosity", priority=2)
                self.journal.add("goal", text_goal, source="curiosity")
                added += 1
            except ValueError:
                continue
        if added > 1:
            pass

    @staticmethod
    def _looks_like_error(text: str) -> bool:
        markers = ("ошибк", "error", "traceback", "urlopen", "winerror", "exception", "поиск не удался")
        low = text.lower()
        return any(m in low for m in markers)

    def ensure_goal(self) -> None:
        if not self.goals.active():
            self.bootstrap(min_goals=1)
        if not self.goals.active():
            self._random_topic_goal()